export const getCategoryInfo = (id) => categories.find(c => c.id === id) || { label: id, icon: '📌', color: 'from-gray-600 to-gray-800' };

export const getStatusColor = (status) => {
  switch (status) {
    case 'open': return 'badge-green';
    case 'active': return 'badge-purple';
    case 'in_progress': return 'badge-blue';
    case 'completed': return 'badge-orange';
    default: return 'badge-purple';
  }
};
